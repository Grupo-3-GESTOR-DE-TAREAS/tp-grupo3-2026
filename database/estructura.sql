CREATE TABLE IF NOT EXISTS materias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    icono VARCHAR(16) NOT NULL DEFAULT '📚',
    color_class VARCHAR(40) NOT NULL DEFAULT 'materia-default',
    color VARCHAR(7) NOT NULL DEFAULT '#e0d5c5',
    creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT materias_nombre_longitud CHECK (char_length(btrim(nombre)) BETWEEN 2 AND 80),
    CONSTRAINT materias_color_formato CHECK (color ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE UNIQUE INDEX IF NOT EXISTS materias_nombre_ci_uq ON materias (lower(btrim(nombre)));

CREATE TABLE IF NOT EXISTS tareas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto VARCHAR(255) NOT NULL,
    completada BOOLEAN NOT NULL DEFAULT FALSE,
    materia_id BIGINT REFERENCES materias(id) ON DELETE SET NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tareas_texto_longitud CHECK (char_length(btrim(texto)) BETWEEN 3 AND 255)
);

CREATE UNIQUE INDEX IF NOT EXISTS tareas_materia_texto_ci_uq
    ON tareas (COALESCE(materia_id, 0), lower(btrim(texto)));
CREATE INDEX IF NOT EXISTS tareas_materia_id_idx ON tareas (materia_id);
CREATE INDEX IF NOT EXISTS tareas_completada_idx ON tareas (completada);

