const test = require('node:test');
const assert = require('node:assert/strict');
const { newDb } = require('pg-mem');
const request = require('supertest');
const { createApp } = require('../../backend/app');

let pool;
let app;

test.before(async () => {
    const database = newDb();
    database.public.none(`
        CREATE TABLE materias (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nombre VARCHAR(80) NOT NULL UNIQUE,
            icono VARCHAR(16) NOT NULL DEFAULT '📚',
            color_class VARCHAR(40) NOT NULL DEFAULT 'materia-default',
            color VARCHAR(7) NOT NULL DEFAULT '#e0d5c5',
            creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE tareas (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            texto VARCHAR(255) NOT NULL,
            completada BOOLEAN NOT NULL DEFAULT FALSE,
            materia_id BIGINT REFERENCES materias(id) ON DELETE SET NULL,
            fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            actualizada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        INSERT INTO materias (id, nombre) VALUES (1001, 'Matemáticas');
    `);
    const adapter = database.adapters.createPg();
    pool = new adapter.Pool();
    app = createApp({ pool });
});

test.after(async () => {
    await pool.end();
});

test('health endpoint checks the database connection', async () => {
    const response = await request(app).get('/api/health').expect(200);
    assert.deepEqual(response.body, { status: 'ok', database: 'connected' });
});

test('task CRUD validates input and persists changes', async () => {
    await request(app).post('/api/tareas').send({ texto: 'x' }).expect(400);

    const created = await request(app)
        .post('/api/tareas')
        .send({ texto: '  Preparar examen  ', materiaId: 1001 })
        .expect(201);
    assert.equal(created.body.texto, 'Preparar examen');
    assert.equal(created.body.completada, false);

    const listed = await request(app).get('/api/tareas').expect(200);
    assert.equal(listed.body.length, 1);
    assert.equal(listed.body[0].texto, 'Preparar examen');

    const updated = await request(app)
        .patch(`/api/tareas/${created.body.id}`)
        .send({ texto: 'Repasar examen', completada: true })
        .expect(200);
    assert.equal(updated.body.texto, 'Repasar examen');
    assert.equal(updated.body.completada, true);

    await request(app).delete(`/api/tareas/${created.body.id}`).expect(204);
    await request(app).delete(`/api/tareas/${created.body.id}`).expect(404);
});

test('subject CRUD preserves tasks and unassigns them when deleted', async () => {
    const createdSubject = await request(app)
        .post('/api/materias')
        .send({ nombre: 'Historia' })
        .expect(201);
    await request(app).post('/api/tareas').send({
        texto: 'Leer capítulo uno',
        materiaId: createdSubject.body.id
    }).expect(201);

    await request(app).delete(`/api/materias/${createdSubject.body.id}`).expect(204);
    const tasks = await request(app).get('/api/tareas').expect(200);
    assert.equal(tasks.body.length, 1);
    assert.equal(tasks.body[0].materiaId, null);
});

test('rejects invalid subject names and malformed JSON', async () => {
    await request(app).post('/api/materias').send({ nombre: 'A' }).expect(400);
    await request(app)
        .post('/api/tareas')
        .set('Content-Type', 'application/json')
        .send('{bad json')
        .expect(400);
});